    fun byProvince(province: String?): List<City> =
        if (province.isNullOrBlank()) all else all.filter { it.province == province }

    fun search(query: String, province: String? = null): List<City> =
        byProvince(province).filter { it.matches(query) }.sortedByDescending { it.radiusKm }

    fun find(id: String): City? = all.firstOrNull { it.id == id }

    fun largest(count: Int): List<City> = all.sortedByDescending { it.radiusKm }.take(count)
