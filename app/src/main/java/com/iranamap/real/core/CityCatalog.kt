/** یک شهر ایران با کادر جغرافیایی تقریبی برای دانلود آفلاین. */
data class City(
    val id: String,
    val name: String,
    val province: String,
    val lat: Double,
    val lng: Double,
    val radiusKm: Double
) {
    val bounds: GeoBounds get() = GeoMath.boundsAround(GeoPoint(lat, lng), radiusKm)
    val minZoom: Int get() = if (radiusKm >= 20) 9 else 10
    val maxZoom: Int get() = if (radiusKm >= 15) 14 else 14
    fun matches(query: String): Boolean {
        val q = PersianText.looseKey(query)
        if (q.isBlank()) return true
        return PersianText.looseKey(name).contains(q) || PersianText.looseKey(province).contains(q)
    }
}

